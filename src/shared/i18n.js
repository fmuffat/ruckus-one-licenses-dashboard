  const LANGUAGES = [
    { id: 'en', name: 'English', locale: 'en-GB' },
    { id: 'de', name: 'Deutsch', locale: 'de-DE' },
    { id: 'es', name: 'Español', locale: 'es-ES' },
    { id: 'fr', name: 'Français', locale: 'fr-FR' },
    { id: 'it', name: 'Italiano', locale: 'it-IT' },
    { id: 'nl', name: 'Nederlands', locale: 'nl-NL' },
    { id: 'pl', name: 'Polski', locale: 'pl-PL' },
    { id: 'pt', name: 'Português', locale: 'pt-PT' },
    { id: 'ja', name: '日本語', locale: 'ja-JP' },
    { id: 'zh', name: '简体中文', locale: 'zh-CN' },
  ];
  const DEFAULT_LANGUAGE = 'en';

  function normalizeLanguage(value) {
    const id = String(value || '').slice(0, 2).toLowerCase();
    return MESSAGES[id] ? id : DEFAULT_LANGUAGE;
  }

  function localeOf(language) {
    return LANGUAGES.find((l) => l.id === language).locale;
  }

  function t(language, key, params = {}) {
    let message = MESSAGES[language]?.[key] ?? MESSAGES[DEFAULT_LANGUAGE][key] ?? key;
    if (typeof message === 'object') {
      // Les règles de pluriel varient : le polonais distingue 1, 2 à 4 et 5 ou plus, par exemple.
      const category = new Intl.PluralRules(localeOf(MESSAGES[language] ? language : DEFAULT_LANGUAGE)).select(params.count ?? 0);
      message = message[category] ?? message.other;
    }
    return message.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined ? match : String(params[name])));
  }

  function typeLabel(language, type) {
    const key = `type.${type}`;
    const label = t(language, key);
    return label === key ? type : label;
  }

  function formatDate(language, ms) {
    return new Date(ms).toLocaleDateString(localeOf(language), { timeZone: 'UTC' });
  }

  // Traduit un message structuré { key, params } venu du cœur de l'application.
  function translate(language, message) {
    const params = { ...(message.params || {}) };
    if (params.type !== undefined) params.type = typeLabel(language, params.type);
    if (params.date !== undefined) params.date = formatDate(language, params.date);
    if (params.whatKey !== undefined) params.what = t(language, params.whatKey);
    return t(language, message.key, params);
  }

  return { MESSAGES, LANGUAGES, DEFAULT_LANGUAGE, normalizeLanguage, localeOf, t, typeLabel, formatDate, translate };
